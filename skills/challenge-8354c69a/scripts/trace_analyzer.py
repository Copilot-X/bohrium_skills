#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Deterministic trace/workbook first pass for result interpretation.

Reads CSV/TSV/JSON tables (and XLSX when openpyxl is available), groups numeric
series by trace/run id, computes trends and robust anomalies, and writes the
five-part work file plus the declared JSON/Markdown artifacts.  Every quoted
row is copied verbatim into work/trace-evidence.md, which finalize can verify.
No causal claim is generated by this script.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import math
import re
from datetime import datetime, timezone
from pathlib import Path

NUM_RE = re.compile(r"^[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?$")


def now_iso():
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def read_json(path, default=None):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return {} if default is None else default


def write_json(path, payload):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    return path


def write_text(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def norm(text):
    return re.sub(r"\s+", " ", str(text or "")).strip()


def number(value):
    text = str(value).strip().replace(",", "")
    if NUM_RE.match(text):
        try:
            return float(text)
        except ValueError:
            return None
    return None


def parse_csv(text):
    lines = [line for line in text.splitlines() if line.strip()]
    if len(lines) < 2:
        return [], []
    delimiter = "\t" if "\t" in lines[0] else (
        ";" if ";" in lines[0] and "," not in lines[0] else ",")
    try:
        rows = list(csv.reader(io.StringIO(text), delimiter=delimiter))
    except csv.Error:
        return [], []
    if len(rows) < 2 or len(rows[0]) < 1:
        return [], []
    return [str(x).strip() for x in rows[0]], rows[1:]


def load_tables(input_dir, materials):
    tables = []
    seen = set()
    for doc in materials.get("documents") or []:
        path = doc.get("path") or doc.get("rel_path") or ""
        if path in seen:
            continue
        seen.add(path)
        text = str(doc.get("text") or "")
        header, rows = parse_csv(text) if text else ([], [])
        if not header and doc.get("rows"):
            header = [str(x) for x in doc["rows"][0]]
            rows = doc["rows"][1:]
        if header and rows:
            tables.append({"path": path, "sheet": "", "header": header,
                           "rows": rows, "text": text})
        data = doc.get("json")
        if isinstance(data, list) and data and isinstance(data[0], dict):
            header = list(data[0])
            rows = [[item.get(key, "") for key in header] for item in data
                    if isinstance(item, dict)]
            if header and rows:
                tables.append({"path": path, "sheet": "", "header": header,
                               "rows": rows, "text": text})
    # XLSX fallback (optional).
    try:
        import openpyxl  # type: ignore
    except Exception:  # noqa: BLE001
        openpyxl = None
    if openpyxl is not None:
        for path in sorted(Path(input_dir).rglob("*.xlsx")):
            try:
                book = openpyxl.load_workbook(path, read_only=True, data_only=True)
            except Exception:  # noqa: BLE001
                continue
            for sheet in book.worksheets:
                rows = list(sheet.iter_rows(values_only=True))
                if len(rows) < 2:
                    continue
                header = [str(x or "").strip() for x in rows[0]]
                body = [[x if x is not None else "" for x in row]
                        for row in rows[1:]]
                if header and body:
                    tables.append({
                        "path": path.relative_to(input_dir).as_posix(),
                        "sheet": sheet.title, "header": header, "rows": body,
                        "text": "\n".join("\t".join(str(x) for x in row)
                                          for row in rows[:2000]),
                    })
    return tables


def compare(a, b):
    return (a > b) - (a < b)


class Series:
    def __init__(self, table, group, metric, xcol, ycol):
        self.table = table
        self.group = group
        self.metric = metric
        self.xcol = xcol
        self.ycol = ycol
        self.points = []

    def add(self, x, y, quote):
        self.points.append({"x": x, "y": y, "quote": quote})


def build_series(tables):
    series = []
    evidence_lines = []
    for table in tables:
        header, rows = table["header"], table["rows"]
        numeric_cols = []
        for index, name in enumerate(header):
            values = [number(row[index]) for row in rows
                      if index < len(row) and number(row[index]) is not None]
            if len(values) >= max(3, len(rows) // 2):
                numeric_cols.append((index, name))
        if not numeric_cols:
            continue
        # Choose x: a time/point/step column if present, else row index.
        x_index = None
        for index, name in enumerate(header):
            if re.search(r"time|step|point|strain|temperature|cycle|x",
                         name, re.I) and any(
                    idx == index for idx, _ in numeric_cols):
                x_index = index
                break
        id_index = None
        for index, name in enumerate(header):
            if re.search(r"trace|run|sample|batch|specimen|id", name, re.I):
                id_index = index
                break
        ycols = [(idx, name) for idx, name in numeric_cols
                 if idx not in (x_index, id_index)]
        if not ycols:
            continue
        for ri, row in enumerate(rows):
            if not row:
                continue
            group = (str(row[id_index]).strip() if id_index is not None
                     and id_index < len(row) else "all")
            x = (number(row[x_index]) if x_index is not None
                 and x_index < len(row) else float(ri))
            if x is None:
                x = float(ri)
            for yi, yname in ycols:
                if yi >= len(row):
                    continue
                y = number(row[yi])
                if y is None:
                    continue
                target = next((s for s in series
                               if s.table is table and s.group == group
                               and s.metric == yname), None)
                if target is None:
                    target = Series(table, group, yname, x_index, yi)
                    series.append(target)
                quote = "\t".join(str(cell).strip() for cell in row)
                target.add(x, y, quote)
                evidence_lines.append({
                    "path": table["path"], "sheet": table["sheet"],
                    "group": group, "metric": yname,
                    "locator": "%s row %d" % (
                        table["sheet"] or "table", ri + 2),
                    "quote": quote,
                })
    return series, evidence_lines


def slope(points):
    if len(points) < 2:
        return 0.0
    xs = [p["x"] for p in points]
    ys = [p["y"] for p in points]
    mx = sum(xs) / len(xs)
    my = sum(ys) / len(ys)
    denom = sum((x - mx) ** 2 for x in xs)
    if denom == 0:
        return 0.0
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / denom


def median(values):
    ordered = sorted(values)
    n = len(ordered)
    if not n:
        return 0.0
    middle = n // 2
    return ordered[middle] if n % 2 else (ordered[middle - 1] + ordered[middle]) / 2


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)
    inp, work, out = Path(args.input), Path(args.work), Path(args.output)
    work.mkdir(parents=True, exist_ok=True)
    out.mkdir(parents=True, exist_ok=True)
    materials = read_json(work / "materials.json", {})
    tables = load_tables(inp, materials)
    series, evidence_lines = build_series(tables)
    # Verbatim evidence table that finalize can quote.
    ev_lines = ["# Trace evidence (verbatim rows)", ""]
    for item in evidence_lines[:5000]:
        ev_lines.append("%s\t%s\t%s\t%s\t%s" % (
            item["path"], item["locator"], item["group"], item["metric"],
            item["quote"]))
    write_text(work / "trace-evidence.md", "\n".join(ev_lines) + "\n")
    observations, trends, anomalies, interpretations = [], [], [], []
    metrics = []
    for s in series:
        if len(s.points) < 2:
            continue
        ys = [p["y"] for p in s.points]
        xs = [p["x"] for p in s.points]
        mean = sum(ys) / len(ys)
        med = median(ys)
        mad = median([abs(y - med) for y in ys]) or 1e-9
        sl = slope(s.points)
        direction = ("up" if sl > 0 else "down" if sl < 0 else "flat")
        label = "%s / %s" % (s.group, s.metric)
        oid = "O%03d" % (len(observations) + 1)
        first = s.points[0]
        last = s.points[-1]
        quote = first["quote"] if first["quote"] else last["quote"]
        locator = "row 2" if first["quote"] else "table"
        observations.append({
            "id": oid, "statement": "%s: x %s→%s, y %s→%s (n=%d)" % (
                label, first["x"], last["x"], first["y"], last["y"],
                len(ys)),
            "value": round(last["y"], 6), "unit": "",
            "run_id": s.group,
            "evidence": {"path": "work/trace-evidence.md",
                         "locator": "row 2", "quote": quote},
        })
        trends.append({
            "id": "T%03d" % (len(trends) + 1), "metric": s.metric,
            "group": s.group, "direction": direction,
            "slope_per_unit": round(sl, 8),
            "interval": "x %s–%s" % (min(xs), max(xs)),
            "mean": round(mean, 6), "median": round(med, 6),
            "n": len(ys),
            "evidence": {"path": "work/trace-evidence.md", "locator": "row 2",
                         "quote": quote},
        })
        # Robust anomaly: |y-med| / (1.4826*MAD) >= 3.5; top 3.
        scored = []
        for point in s.points:
            z = abs(point["y"] - med) / (1.4826 * mad)
            if z >= 3.5:
                scored.append((z, point))
        scored.sort(reverse=True, key=lambda x: x[0])
        for z, point in scored[:3]:
            anomalies.append({
                "id": "A%03d" % (len(anomalies) + 1),
                "observation_id": oid, "run_id": s.group,
                "value": round(point["y"], 6),
                "threshold": "robust z >= 3.5 (median/MAD)",
                "method": "median absolute deviation",
                "severity": "high" if z >= 6 else "medium",
                "action": "re-read the raw trace and repeat if the deviation persists",
                "evidence": {"path": "work/trace-evidence.md",
                             "locator": "row 2", "quote": point["quote"]},
            })
        metrics.append({"group": s.group, "metric": s.metric,
                        "n": len(ys), "slope": sl})
    # Association-only interpretations (never causal).
    for trend in trends[:12]:
        interpretations.append({
            "id": "I%03d" % (len(interpretations) + 1),
            "statement": "%s shows a %s association; mechanism not established" % (
                trend["metric"], trend["direction"]),
            "type": "association", "strength": "suggestive",
            "support": [trend["id"]],
            "exclusion": ["no controlled intervention in the supplied traces"],
            "confounders": ["trace/sample identity", "time-dependent drift"],
            "evidence": trend["evidence"],
        })
    recheck = [{
        "id": "RC%03d" % (index + 1),
        "action": "Re-read the raw source rows for %s and confirm the x/y units and trace id." % t["metric"],
        "observation_id": next((o["id"] for o in observations
                                if o["run_id"] == t["group"]), observations[0]["id"] if observations else ""),
        "expected": "same values and units as work/trace-evidence.md",
        "evidence": t["evidence"],
    } for index, t in enumerate(trends[:5])]
    follow = [{
        "id": "E%03d" % (index + 1),
        "experiment": "controlled repeat of %s with the same x grid and logged conditions" % t["metric"],
        "purpose": "separate a real response from trace/sample artifacts",
        "observation_id": next((o["id"] for o in observations
                                if o["run_id"] == t["group"]), observations[0]["id"] if observations else ""),
        "expected_outcome": "same direction and comparable magnitude",
        "decision_rule": "replicate within the robust 95% interval; otherwise mark unstable",
        "evidence": t["evidence"],
    } for index, t in enumerate(trends[:5])]
    plan = {
        "case_id": read_json(inp / "case.json", {}).get("case_id") or "UNKNOWN",
        "mode": "result-interpretation",
        "summary": "从 %d 个表、%d 条序列中提取 %d 个观测、%d 个趋势、%d 个异常；只写关联，不写因果。" % (
            len(tables), len(series), len(observations), len(trends), len(anomalies)),
        "observations": observations, "trends": trends,
        "anomalies": anomalies, "interpretations": interpretations,
        "alternative_explanations": [{
            "id": "ALT1", "explanation": "trace/sample identity or time drift explains the pattern",
            "status": "untested", "test": "controlled repeat with shuffled trace order"}],
        "recheck_steps": recheck, "next_experiments": follow,
        "evidence": [{"path": "work/trace-evidence.md", "locator": "row 2",
                      "quote": (evidence_lines[0]["quote"] if evidence_lines else "")}]
        if evidence_lines else [],
        "risks": [{"risk": "raw trace provenance or units may be ambiguous",
                   "severity": "major",
                   "mitigation": "re-read the source row and confirm units"}],
        "analysis": {"method": "grouped slope + median/MAD robust anomaly",
                     "assumptions": ["x is monotone within a trace", "rows are independent"],
                     "diagnostics": [{"tables": len(tables), "series": len(series)}]},
        "results": metrics,
        "uncertainties": [{"item": "causal_mechanism",
                           "reason": "the supplied data are observational traces",
                           "impact": "only associations are reported",
                           "action": "run the follow-up controlled experiment"}],
        "generated_at": now_iso(), "generated_by": "trace_analyzer.py",
    }
    write_json(work / "experiment-plan.json", plan)
    write_json(out / "interpretation.json", {
        "case_id": plan["case_id"], "interpretations": interpretations})
    write_json(out / "anomalies.json", {
        "case_id": plan["case_id"], "anomalies": anomalies,
        "recheck_steps": recheck})
    write_json(out / "follow-up.json", {
        "case_id": plan["case_id"], "next_experiments": follow})
    report = ["# 实验结果解释与异常分析", "",
              "> 由 trace_analyzer.py 从真实表/轨迹重算；只报告关联，不写因果。", "",
              "## 趋势", ""]
    for t in trends[:20]:
        report.append("- %s：%s（%s，斜率 %.6g，n=%d）" % (
            t["metric"], t["direction"], t["interval"], t["slope_per_unit"], t["n"]))
    report += ["", "## 异常点", ""]
    if anomalies:
        for a in anomalies[:20]:
            report.append("- %s / %s = %.6g（%s）" % (
                a["run_id"], a["observation_id"], a["value"], a["threshold"]))
    else:
        report.append("- 未发现超过稳健阈值的异常点。")
    report += ["", "## 可能原因（关联，非因果）", ""]
    for item in interpretations[:12]:
        report.append("- %s：%s" % (item["id"], item["statement"]))
    report += ["", "## 复核步骤", ""]
    for item in recheck:
        report.append("- %s：%s" % (item["id"], item["action"]))
    report += ["", "## 后续实验", ""]
    for item in follow:
        report.append("- %s：%s；判读：%s" % (
            item["id"], item["experiment"], item["decision_rule"]))
    write_text(out / "experiment-report.md", "\n".join(report) + "\n")
    summary = {"ok": bool(observations), "tables": len(tables),
               "series": len(series), "observations": len(observations),
               "trends": len(trends), "anomalies": len(anomalies)}
    print(json.dumps(summary, ensure_ascii=False, indent=2)
          if args.json else json.dumps(summary, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
