#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Single entry point for the journal-format-adapter skill.

    python3 scripts/main.py --input /input --output /app/output --work /app/work --json

The pipeline always writes result.json (even for partial/input_error) and exits
0. Exit 2 is reserved for the case where the output directory itself cannot be
created. Body text is never generated by this script: it is either the source
manuscript copied verbatim, or a model-supplied body passed with --body.
"""
import argparse
import importlib
import importlib.util
import json
import shutil
import sys
import traceback
from importlib.machinery import SourceFileLoader
from pathlib import Path


def load_sibling(name):
    try:
        return importlib.import_module(name)
    except Exception:  # noqa: BLE001
        pass
    base = Path(__file__).resolve().parent
    for candidate in (base / f"{name}.py", base / f"{name}.py.md"):
        if candidate.is_file():
            try:
                loader = SourceFileLoader(f"_format_{name}", str(candidate))
                spec = importlib.util.spec_from_loader(f"_format_{name}", loader)
                module = importlib.util.module_from_spec(spec)
                loader.exec_module(module)
                return module
            except Exception:  # noqa: BLE001
                return None
    return None


def artifact(path, role, fmt):
    path = Path(path)
    if not path.is_file() or path.stat().st_size == 0:
        return None
    return {"path": path.name, "role": role, "format": fmt,
            "bytes": path.stat().st_size}


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2),
                    encoding="utf-8")
    return path


def minimal_result(output_dir, case_id, reason, status="partial"):
    result = {
        "case_id": case_id or "unknown-case",
        "task_family": "format-adaptation",
        "status": status,
        "deliverable": None,
        "preserved_facts": [],
        "evidence_map": [],
        "change_log": [],
        "artifacts": [],
        "requirements": [],
        "summary": {"total": 0, "pass": 0, "fixed": 0, "missing": 0,
                    "not_applicable": 0, "manual_check": 0},
        "unmet": [{"id": "U00", "requirement": "pipeline execution",
                   "reason": reason,
                   "impact": "no adapted manuscript was produced"}],
        "uncertainty": [{"kind": "pipeline_unavailable", "detail": reason,
                         "impact": "partial result only"}],
    }
    write_json(Path(output_dir) / "result.json", result)
    return result


def _source_text(source_units):
    if source_units.get("text"):
        return source_units["text"]
    return "\n".join(paragraph.get("text") or ""
                     for paragraph in source_units.get("paragraphs") or [])


def run_pipeline(args):
    input_dir = Path(args.input)
    output_dir = Path(args.output)
    work_dir = Path(args.work)
    output_dir.mkdir(parents=True, exist_ok=True)
    work_dir.mkdir(parents=True, exist_ok=True)
    adapter = load_sibling("adapter")
    docio = load_sibling("docio")
    if adapter is None or docio is None:
        reason = "scripts/adapter.py or scripts/docio.py is unavailable"
        minimal_result(output_dir, None, reason)
        return 0

    uncertainty, unmet, commands = [], [], []
    def note(kind, detail, impact="result quality may be reduced"):
        uncertainty.append({"kind": kind, "detail": str(detail)[:800],
                            "impact": impact})

    scan = adapter.scan_input(input_dir)
    case = adapter.load_case(input_dir)
    if not input_dir.is_dir():
        note("input_missing", f"input directory not found: {input_dir}",
             "no source material")
    if not case.get("path"):
        note("case_json_missing", "no case JSON with case_id/output_contract found",
             "case identification is inferred from filenames")

    source_path = Path(args.source) if args.source else \
        (Path(scan["manuscript"]) if scan.get("manuscript") else None)
    template_path = Path(args.template) if args.template else \
        (Path(scan["template"]) if scan.get("template") else None)
    guide_path = Path(scan["guide"]) if scan.get("guide") else None
    body_path = Path(args.body) if args.body else None

    # ---- style guide -----------------------------------------------------
    guide = {"guide_name": None}
    if guide_path is not None:
        guide_text_path, guide_error = adapter.ensure_text_file(
            guide_path, work_dir, "guide")
        if guide_text_path:
            guide = adapter.parse_guide_text(
                adapter.read_text(guide_text_path), guide_path.name)
            guide["guide_name"] = guide_path.name
        else:
            note("guide_unreadable", guide_error or str(guide_path),
                 "format requirements from the guide are unavailable")
    elif case.get("task") and isinstance(case["task"], str):
        parsed = adapter.parse_guide_text(case["task"], "case instruction")
        if parsed.get("recognized"):
            parsed["guide_name"] = "case instruction"
            guide = parsed

    # ---- source ----------------------------------------------------------
    blocks = None
    title_text = None
    source_units = {"paragraphs": [], "counts": {}}
    source_name = None
    source_is_docx = False
    body_mode = "source-preserved"
    if body_path is not None:
        if not body_path.is_file():
            note("body_missing", f"--body file not found: {body_path}",
                 "falling back to the source manuscript body")
        elif body_path.suffix.lower() == ".docx":
            source_path = body_path
            source_is_docx = True
            body_mode = "model-docx"
        else:
            parsed = docio.read_source_blocks(body_path)
            blocks = parsed.get("blocks") or []
            title_text = parsed.get("title")
            source_units = adapter.units_from_blocks(blocks, body_path.name,
                                                     title_text)
            source_name = body_path.name
            source_path = body_path
            source_is_docx = False
            body_mode = "model-markdown"
    if source_path is not None and source_path.is_file():
        suffix = source_path.suffix.lower()
        if suffix == ".pdf":
            converted, conversion_error = adapter.ensure_text_file(
                source_path, work_dir, "manuscript")
            if converted:
                source_path = Path(converted)
                suffix = ".txt"
            else:
                note("source_pdf_unreadable", conversion_error or str(source_path),
                     "manuscript text could not be extracted")
        if suffix == ".docx":
            if blocks is None:
                source_is_docx = True
                inventory = docio.docx_read(source_path)
                if not inventory.get("ok"):
                    note("source_docx_unreadable", inventory.get("error"),
                         "manuscript DOCX could not be read")
                else:
                    source_units = adapter.units_from_docx_inventory(
                        inventory, source_path.name)
                    source_name = source_path.name
        elif suffix in (".md", ".txt", ".tex", ".latex", ".rst", ".org"):
            if blocks is None:
                parsed = docio.read_source_blocks(source_path)
                blocks = parsed.get("blocks") or []
                title_text = parsed.get("title")
                source_units = adapter.units_from_blocks(
                    blocks, source_path.name, title_text)
                source_name = source_path.name
    if source_name is None and blocks is not None:
        source_name = body_path.name if body_path else "source"
    if not source_units.get("paragraphs") and not source_is_docx and blocks is None:
        note("source_missing", "no readable manuscript source under the input directory",
             "no deliverable can be produced")
        result = adapter.build_result(
            case, scan, adapter.default_spec(), None,
            str(source_path) if source_path else None,
            None, [], [], {"total": 0, "pass": 0, "fixed": 0, "missing": 0,
                           "not_applicable": 0, "manual_check": 0},
            {}, [], [], [], [], [], [], source_units, {}, body_mode, commands)
        result["status"] = "input_error"
        result["unmet"].append({
            "id": "U-SOURCE", "requirement": "manuscript source",
            "reason": "no readable manuscript was found under /input",
            "impact": "no DOCX deliverable was produced"})
        write_json(output_dir / "result.json", result)
        return 0

    # ---- template spec ---------------------------------------------------
    if template_path is not None and template_path.is_file():
        spec = adapter.extract_template_spec(template_path)
        if (spec.get("meta") or {}).get("template_readable") is False:
            unmet.append({
                "id": "U-TEMPLATE-READ", "requirement": "template.docx",
                "reason": "the template DOCX could not be opened as a valid "
                          "Word package",
                "impact": "built-in defaults were used; the deliverable is partial"})
    else:
        spec = adapter.default_spec()
        unmet.append({
            "id": "U-TEMPLATE", "requirement": "template.docx",
            "reason": "no template DOCX candidate was found under /input",
            "impact": "built-in defaults and the guide were used; template-specific "
                      "styles could not be read"})
    spec = adapter.merge_spec(spec, guide, case)
    font_substitutions = adapter.apply_font_revision(spec)

    spec_path = work_dir / "format-spec.json"
    write_json(spec_path, spec)

    # ---- produce the DOCX ------------------------------------------------
    out_docx = output_dir / "manuscript.docx"
    build_report = None
    apply_report = None
    try:
        if source_is_docx and source_path is not None and body_mode != "model-markdown":
            apply_report = docio.apply_docx(source_path, spec, out_docx)
        else:
            if blocks is None and source_path is not None:
                parsed = docio.read_source_blocks(source_path)
                blocks = parsed.get("blocks") or []
                title_text = parsed.get("title") or title_text
            build_report = docio.build_docx(
                blocks or [], spec, out_docx,
                str(template_path) if template_path and template_path.is_file() else None,
                title=title_text)
    except Exception as exc:  # noqa: BLE001
        note("docx_write_failed", f"{type(exc).__name__}: {exc}",
             "trying the built-in package skeleton")
        try:
            if blocks is None and source_path is not None and \
                    source_path.suffix.lower() in (".md", ".txt", ".tex"):
                parsed = docio.read_source_blocks(source_path)
                blocks = parsed.get("blocks") or []
                title_text = parsed.get("title") or title_text
            build_report = docio.build_docx(blocks or [], spec, out_docx, None,
                                            title=title_text)
        except Exception as second:  # noqa: BLE001
            note("docx_fallback_failed", f"{type(second).__name__}: {second}",
                 "no DOCX deliverable")

    output_check = docio.check_docx(out_docx) if out_docx.is_file() else {
        "ok": False, "error": "manuscript.docx was not produced"}
    output_inventory = docio.docx_read(out_docx) if out_docx.is_file() else {
        "ok": False, "paragraphs": [], "styles": {}, "counts": {}}
    deliverable = None
    if output_check.get("ok"):
        deliverable = {
            "path": "manuscript.docx", "format": "docx", "role": "editable",
            "bytes": out_docx.stat().st_size,
            "sha256": adapter.sha256_file(out_docx),
            "readback": {"paragraphs": output_check.get("paragraphs"),
                         "page": (output_check.get("page") or {}).get("name"),
                         "margins_cm": output_check.get("margins_cm")},
        }
    else:
        fallback = output_dir / "manuscript.md"
        if blocks is not None:
            lines = []
            if blocks:
                for block in blocks:
                    kind = block.get("type")
                    if kind == "heading":
                        lines.append("#" * int(block.get("level") or 1) + " " +
                                     block.get("text", ""))
                    elif kind == "paragraph":
                        lines.append(block.get("text", ""))
                    elif kind in ("bullets", "numbers"):
                        lines.extend(f"- {item}" for item in block.get("items") or [])
                    elif kind == "table":
                        rows = [block.get("header") or []] + (block.get("rows") or [])
                        lines.extend("| " + " | ".join(row) + " |" for row in rows)
                        if block.get("caption"):
                            lines.append(block["caption"])
                    elif kind == "figure" and block.get("caption"):
                        lines.append(block["caption"])
                fallback.write_text("\n\n".join(lines), encoding="utf-8")
                deliverable = {"path": "manuscript.md", "format": "md",
                               "role": "editable_fallback",
                               "bytes": fallback.stat().st_size}
                unmet.append({
                    "id": "U-DOCX", "requirement": "manuscript.docx",
                    "reason": output_check.get("error") or "DOCX read-back failed",
                    "impact": "an editable Markdown fallback was delivered instead"})
        if deliverable is None:
            unmet.append({
                "id": "U-DELIVERABLE", "requirement": "deliverable",
                "reason": output_check.get("error") or "no deliverable could be written",
                "impact": "the run is partial"})

    # ---- fidelity, requirements, facts -----------------------------------
    source_text = _source_text(source_units)
    output_text = output_check.get("body_text") or ""
    fidelity = adapter.fidelity_record(
        source_text, output_text, source_units, output_inventory,
        source_name, deliverable.get("path") if deliverable else None)
    requirements = adapter.requirement_catalog(spec)
    requirements = adapter.verify_requirements(
        requirements, spec, output_check, output_inventory, source_units, fidelity)
    summary = adapter.summarize(requirements)
    preserved_facts = adapter.build_preserved_facts(
        source_units, output_inventory, source_name or "source",
        (deliverable or {}).get("path") or "manuscript.docx")
    evidence_map = adapter.build_evidence_map(
        requirements, (deliverable or {}).get("path") or "manuscript.docx")
    change_log = adapter.build_change_log(
        spec, template_path.name if template_path else None, source_name,
        (deliverable or {}).get("path") or "manuscript.docx",
        font_substitutions, body_mode.startswith("model"))

    # ---- artifacts -------------------------------------------------------
    shutil.copyfile(spec_path, output_dir / "format-spec.json")
    output_check_path = output_dir / "docx-check.json"
    write_json(output_check_path, output_check)
    source_inventory_path = output_dir / "source-inventory.json"
    write_json(source_inventory_path, {
        "input": str(input_dir), "scan": scan,
        "source_units": source_units.get("counts"),
        "source": source_name, "template": str(template_path) if template_path else None,
        "guide": str(guide_path) if guide_path else None})
    artifacts = [
        artifact(out_docx, "editable_manuscript", "docx"),
        artifact(output_dir / "format-spec.json", "format_spec", "json"),
        artifact(output_check_path, "docx_check", "json"),
        artifact(source_inventory_path, "source_inventory", "json"),
        artifact(output_dir / "manuscript.md", "fallback_markdown", "md"),
    ]
    if build_report and build_report.get("warnings"):
        note("build_warnings", "; ".join(build_report["warnings"][:8]))
    if apply_report and apply_report.get("warnings"):
        note("apply_warnings", "; ".join(apply_report["warnings"][:8]))
    if spec.get("meta", {}).get("unrecognized"):
        note("guide_unrecognized",
             f"{len(spec['meta']['unrecognized'])} guide line(s) contained format "
             f"terms but could not be parsed; see format-spec.json")
    manual = [item["id"] for item in requirements
              if item.get("status") == "manual_check"]
    if manual:
        note("manual_checks", f"{len(manual)} requirement(s) need visual/Word checks: "
             f"{', '.join(manual[:10])}")
    if (spec.get("meta") or {}).get("conflicts"):
        note("spec_conflicts",
             f"{len(spec['meta']['conflicts'])} guide/template conflict(s); "
             f"guide values were applied and recorded")

    result = adapter.build_result(
        case, scan, spec, spec_path, str(source_path) if source_path else None,
        deliverable, artifacts, requirements, summary, fidelity,
        font_substitutions, change_log, preserved_facts, evidence_map,
        uncertainty, unmet, source_units, output_check, body_mode, commands)
    write_json(output_dir / "result.json", result)
    (output_dir / "adaptation-report.md").write_text(
        adapter.render_report_md(result), encoding="utf-8")
    if args.json:
        print(json.dumps({
            "status": result.get("status"),
            "case_id": result.get("case_id"),
            "deliverable": deliverable,
            "summary": summary,
            "fidelity": fidelity.get("similarity"),
            "template": str(template_path) if template_path else None,
            "guide": str(guide_path) if guide_path else None,
            "body_mode": body_mode,
            "unmet": [item.get("id") for item in unmet],
        }, ensure_ascii=False, indent=2))
    return 0


def main():
    parser = argparse.ArgumentParser(description="Journal format adapter")
    parser.add_argument("--input", default="/input")
    parser.add_argument("--output", default="/app/output")
    parser.add_argument("--work", default="/app/work")
    parser.add_argument("--source", default=None,
                        help="explicit manuscript file (overrides input triage)")
    parser.add_argument("--template", default=None,
                        help="explicit template DOCX (overrides input triage)")
    parser.add_argument("--body", default=None,
                        help="model-authored body (.md/.txt) or DOCX to restyle")
    parser.add_argument("--skill-dir", default=None)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    try:
        Path(args.output).mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        print(json.dumps({"status": "error", "detail": str(exc)}), file=sys.stderr)
        return 2
    try:
        return run_pipeline(args)
    except Exception as exc:  # noqa: BLE001
        traceback.print_exc()
        minimal_result(args.output, None,
                       f"{type(exc).__name__}: {exc}", status="partial")
        return 0


if __name__ == "__main__":
    sys.exit(main())
